/**
 * Builds the two logo files the apps use from the owner's original artwork (2026-11-07).
 *
 *   source:  packages/ui/assets/logo-source.svg   (the designer's file, kept unchanged; replace it to update the logo)
 *   output:  packages/ui/assets/logo.svg          full badge: ring lettering "SPIRIT OF SANTA" + gift (header, share image)
 *            packages/ui/assets/logo-icon.svg     simple badge: gift only, no lettering or outer ring (tab + phone icons,
 *                                                 where tiny lettering turns into noise)
 *            packages/ui/src/brand-art.generated.ts  both as data: URLs, for the PNG renderers (icons, share image),
 *                                                 which can't load files by URL at build time
 *
 * Run after replacing the source:   npm run brand:logo
 *
 * What it changes (and why):
 *  - Removes the <text> elements. The designer's file has the lettering TWICE: as gold outlines (what you see) and
 *    as plain black text in "Playfair Display", hidden behind them. On a device without that font, the black copy
 *    could show through, so only the outlines stay.
 *  - Square canvas centred on the badge (the original had empty space above the circle, so it sat low).
 *  - svgo shrinks the file (rounding, merging styles). Visual result is the same.
 * The regexes below match THIS designer file's structure; if a new source looks different, check the output
 * and open both SVGs in a browser after running.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { optimize } from "svgo";

const DIR = new URL("../../packages/ui/assets/", import.meta.url);
const source = readFileSync(new URL("logo-source.svg", DIR), "utf8");

/** Replace exactly `count` matches (or at least one when count is omitted), else fail loudly. */
function cut(svg, re, replacement, count) {
  const found = svg.match(new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g"))?.length ?? 0;
  if (found === 0 || (count !== undefined && found !== count)) {
    throw new Error(`expected ${count ?? "≥1"} match(es) of ${re}, found ${found}: has the source file changed?`);
  }
  return svg.replace(re, replacement);
}

const viewBox = (svg, box) => cut(svg, /viewBox="[^"]*"/, `viewBox="${box}"`, 1);

// Shared clean-up: drop the hidden duplicate lettering (<text> elements).
const noText = cut(source, /<text\b[\s\S]*?<\/text>/g, "");

// FULL logo: the outer gold ring is a circle of radius 104 around (106.5, 134.02) → a 208-wide square.
const full = viewBox(noText, "2.5 30.02 208 208");

// ICON: also drop the lettering outlines (class cls-180) and the outer ring (Path_728-2), shrink the red disc to the
// inner gold ring (radius ~84 around (106.4, 134.1)) and crop to it with a small margin.
let icon = cut(noText, /<path class="cls-180"[^>]*\/>/g, "", 13); // S-P-I-R-I-T O-F S-A-N-T-A
icon = cut(icon, /<path id="Path_728-2"[^>]*\/>/g, "", 1);
icon = cut(icon, /(<circle class="cls-188" [^>]*?)r="102\.29"/, '$1r="84"', 1);
icon = viewBox(icon, "20.4 48.1 172 172");

const svgoConfig = {
  multipass: true,
  floatPrecision: 2,
  plugins: [{ name: "preset-default" }, "removeDimensions"],
};

const outputs = { "logo.svg": full, "logo-icon.svg": icon };
const dataUrls = {};
for (const [name, svg] of Object.entries(outputs)) {
  const { data } = optimize(svg, svgoConfig);
  writeFileSync(new URL(name, DIR), data + "\n");
  dataUrls[name] = "data:image/svg+xml;base64," + Buffer.from(data).toString("base64");
  console.log(`${name}: ${data.length} bytes (${gzipSync(data, { level: 9 }).length} gzipped)`);
}

writeFileSync(
  new URL("../../packages/ui/src/brand-art.generated.ts", import.meta.url),
  `// GENERATED by scripts/brand/build-logo.mjs (npm run brand:logo). Do not edit by hand.
// The logo artwork as data: URLs for the PNG renderers (app icons, share image). Server-side only:
// never import this into a Client Component (it would add the artwork to the browser bundle).
import "server-only";

/** Full badge with the ring lettering (share image). */
export const LOGO_DATA_URL =
  ${JSON.stringify(dataUrls["logo.svg"])};

/** Simple badge, gift only (tab + phone icons). */
export const LOGO_ICON_DATA_URL =
  ${JSON.stringify(dataUrls["logo-icon.svg"])};
`,
);
console.log("wrote packages/ui/src/brand-art.generated.ts");
